"""Write the config for one round of the main equal-depth study and print the reuse sources.

Two groups, run as separate output directories (different depths and GPU packing):
  small : n = 10,12,14,16   depths 1,2,3,4,6
  large : n = 18,20,22      depths 1,2,3,4
  n18p6 : n = 18            depths 1,2,3,4,6  (p=1-4 imported from the large group; only p=6 computed)
Round N = N training instances per (n, family, weight) cell; val/test stay fixed (10/20 per cell).
Optimization in complex64 (ftol 1e-6, gtol 1e-3); every final energy and all fit/test energies are
re-evaluated in complex128 (see cdtransfer/eqdepth.py).
Instance j of a cell is the same graph in every round (seed = hash(seed, split, n, family, weight, j)),
so round 40 = round 20 + 20 new instances per cell, and finished optimizations are imported.

Usage (normally called by scripts/run_rounds.sh):
  python scripts/23_round_config.py --group small --n-train 20
prints two lines:  CONFIG_PATH  OUT_DIR  and  REUSE=dir1,dir2,...  (existing earlier runs)
"""
from __future__ import annotations
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FAMILIES = ["tree", "ring", "regular3", "regular4", "regular5", "regular6",
            "er3", "er05", "community", "bipartite"]
WEIGHTS = ["unit", "uniform", "bimodal", "lognormal", "heavy_tail"]
GROUPS = {
    "small": {"n": [10, 12, 14, 16], "depths": [1, 2, 3, 4, 6]},
    "large": {"n": [18, 20, 22], "depths": [1, 2, 3, 4]},
    "n18p6": {"n": [18], "depths": [1, 2, 3, 4, 6], "reuse_groups": ["large"]},
}
VAL_PER_CELL, TEST_PER_CELL = 10, 20


def make_config(group: str, n_train: int) -> dict:
    g = GROUPS[group]

    def split(samples):
        return {"n": g["n"], "families": FAMILIES, "weights": WEIGHTS, "samples_per_cell": samples}
    return {
        "_note": f"main study, group {group}, round {n_train}/{VAL_PER_CELL}/{TEST_PER_CELL} per cell; "
                 f"generated by scripts/23_round_config.py",
        "comparison": "same_depth", "seed": 20261013, "depths": g["depths"], "shots": 0,
        "exact_max_n": 24,
        "execution": {"backend": "lightning.gpu", "dtype": "complex64",
                      "gpus": "0,1,2,3,4,5,6,7", "slots_per_gpu": 1, "task_weight_by_n": {}},
        "optimization": {"restarts": 8, "maxiter": 200, "ftol": 1e-6, "gtol": 1e-3},
        "datasets": {"train": split(n_train), "val": split(VAL_PER_CELL), "test": split(TEST_PER_CELL)},
    }


def reuse_sources(group: str, out: Path) -> list[str]:
    """Every existing round of this group (and of the groups it shares instances with).  Older
    complex128 directories are not listed: their dtype/ftol/gtol differ, so nothing would be imported.
    Same (n, family, weight, j) -> same graph in every group, so shared depths are imported."""
    found = []
    for g in [group] + GROUPS[group].get("reuse_groups", []):
        for d in sorted((ROOT / "results").glob(f"eqdepth_{g}_N*")):
            if re.fullmatch(rf"eqdepth_{g}_N\d+", d.name) and d.resolve() != out.resolve():
                found.append(d)
    return [str(d.relative_to(ROOT)) for d in found if (d / "checkpoints").is_dir()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--group", choices=sorted(GROUPS), required=True)
    ap.add_argument("--n-train", type=int, required=True, help="training instances per cell (20, 40, ...)")
    args = ap.parse_args()
    if args.n_train < 1:
        raise SystemExit("--n-train must be >= 1")
    cfg_path = ROOT / "configs" / "rounds" / f"eqdepth_{args.group}_N{args.n_train}.json"
    out = ROOT / "results" / f"eqdepth_{args.group}_N{args.n_train}"
    cfg_path.parent.mkdir(parents=True, exist_ok=True)
    cfg_path.write_text(json.dumps(make_config(args.group, args.n_train), indent=1) + "\n")
    print(cfg_path.relative_to(ROOT), out.relative_to(ROOT))
    print("REUSE=" + ",".join(reuse_sources(args.group, out)))


if __name__ == "__main__":
    main()
